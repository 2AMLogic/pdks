# ihp_osdi VA_DIR OUT_DIR MODEL...: compile each VA_DIR/<model>/<model>.va
# (psp103_nqs lives in psp103/) to OUT_DIR/<model>.osdi with the flags of
# IHP's own libs.tech/verilog-a/openvaf-compile-va.sh. Written to our own
# directory: the PDK's script writes into its tracked tree, which for
# SG13CMOS5L holds prebuilt Linux-only binaries.
ihp_osdi() {
  local va=$1 out=$2 m src; shift 2
  mkdir -p "$out"
  for m in "$@"; do
    case $m in psp103_nqs) src="$va/psp103/psp103_nqs.va" ;; *) src="$va/$m/$m.va" ;; esac
    compile_va "$src" "$out/$m.osdi" -D__NGSPICE__
  done
}

# ihp_glue PDK MODELS_DIR OSDI_DIR MODEL...: write ngspice/spiceinit (and a
# .spiceinit copy) loading each .osdi by absolute path, example.sp, and the
# mismatch and noise examples.
ihp_glue() {
  local pdk=$1 models=$2 osdi=$3 m; shift 3
  local ng="$PREFIX/$pdk/ngspice"
  mkdir -p "$ng"
  {
    echo "* ngspice settings for $pdk (generated by bootstrap.sh). Copy to"
    echo "* ~/.spiceinit or to your simulation directory as .spiceinit."
    echo "* Same OSDI set as the PDK's own .spiceinit, with absolute paths"
    echo "* instead of \$PDK_ROOT/\$PDK."
    for m in "$@"; do echo "osdi '$osdi/$m.osdi'"; done
  } > "$ng/spiceinit"
  cp "$ng/spiceinit" "$ng/.spiceinit"
  render "$REPO/ngspice/ihp/example.sp.in" "$ng/example.sp" \
    "MODELS_DIR=$models" "NGSPICE=$NGSPICE" "PDK=$pdk"
  # Mismatch (Monte Carlo) and noise decks for the LV (1.2 V) and HV (3.3 V)
  # nMOS: mismatch.sp / noise.sp and mismatch_hv.sp / noise_hv.sp. The same
  # templates serve both PDKs (their MOS models are the same PSP 103 cards).
  # Both templates take a polarity (POL): the sanity checks render them for
  # the pMOS too, the installed examples stay nMOS-only, so POL is 1 here and
  # every bias is positive. POL and VGSTEP must be passed: bootstrap.sh's
  # render() is a bare sed and would leave an unfilled @POL@ in the deck.
  local c sfx lt dev vdd vds vg vglo vghi
  for c in LV HV; do
    if [ "$c" = LV ]; then
      sfx="" lt=lv dev=sg13_lv_nmos vdd=1.2 vds=0.05 vg=0.7 vglo=0.698 vghi=0.702
    else
      sfx="_hv" lt=hv dev=sg13_hv_nmos vdd=3.3 vds=0.1 vg=1.5 vglo=1.498 vghi=1.502
    fi
    render "$REPO/ngspice/ihp/mismatch.sp.in" "$ng/mismatch$sfx.sp" "PDK=$pdk" "CLASS=$c" \
      "DECK=mismatch$sfx.sp" "MODELS_DIR=$models" "NGSPICE=$NGSPICE" "LIBTAG=$lt" "DEV=$dev" \
      POL=1 "VDD=$vdd" "VDS=$vds" VGSTEP=0.002 W=4 L=4 M=1 N=100 MM=1 SEED=1
    render "$REPO/ngspice/ihp/noise.sp.in" "$ng/noise$sfx.sp" "PDK=$pdk" "CLASS=$c" \
      "DECK=noise$sfx.sp" "MODELS_DIR=$models" "NGSPICE=$NGSPICE" "LIBTAG=$lt" "DEV=$dev" \
      POL=1 W=10 L=10 "VG=$vg" "VD=$vdd" "VGLO=$vglo" "VGHI=$vghi"
  done
}
