# Tokai Rika TR-1um setup, sourced by bootstrap.sh (which provides the helpers).
# shellcheck shell=bash

# shellcheck source=pdks/tr1um/upstream.lock
. "$REPO/pdks/tr1um/upstream.lock"
GUARD_DIRS+=("$PREFIX/tr1um")

setup_tr1um() {
  local root="$PREFIX/tr1um" ng="$PREFIX/tr1um/ngspice"
  local id; id="tr1um $TR1UM_COMMIT $(files_id "$REPO/pdks/tr1um/setup.sh" "$REPO/pdks/tr1um/files.sha256" "$REPO/ngspice/wire.inc" "$REPO/pdks/tr1um/interconnect.csv" "$REPO"/ngspice/tr1um/*.in)"
  if stamp_ok "$root" "$id"; then
    log "TR-1um: already set up"
    return
  fi
  log "TR-1um: fetching SPICE models at $TR1UM_COMMIT"
  claim_dir "$root"
  local f sum
  while read -r sum f; do
    fetch "$TR1UM_RAW/$f" "$sum" "$root/TR-1um/$f"
  done < "$REPO/pdks/tr1um/files.sha256"
  # No adaptations for the MOSFETs: they load in ngspice unchanged.
  mkdir -p "$ng"
  render "$REPO/ngspice/tr1um/example.sp.in" "$ng/example.sp" \
    "MODELS_DIR=$root/TR-1um/libs.tech/spice/models" "NGSPICE=$NGSPICE"
  log "TR-1um: installing interconnect table and wire include"
  cp "$REPO/pdks/tr1um/interconnect.csv" "$REPO/ngspice/wire.inc" "$ng/"
  # Geometry as .param tr1um_<layer>_<w|s|t|p|h>, in metres (the table is in
  # um). Gaps (no published value) are left out, so using one is an
  # unknown-parameter error.
  awk -F, 'NR > 1 && $5 != "gap" && ($2 in k) {
    printf ".param tr1um_%s_%s=%su\n", tolower($1), k[$2], $3
  }
  BEGIN { k["width_min"] = "w"; k["spacing_min"] = "s"; k["thickness"] = "t"; k["pitch"] = "p"; k["height"] = "h"
    print "* Generated by bootstrap.sh from interconnect.csv (published / derived values only)." }' \
    "$ng/interconnect.csv" > "$ng/interconnect.inc"
  # No mismatch deck: the models carry no statistical parameters (see README).
  render "$REPO/ngspice/tr1um/noise.sp.in" "$ng/noise.sp" \
    "MODELS_DIR=$root/TR-1um/libs.tech/spice/models" "NGSPICE=$NGSPICE" \
    W=30 L=10 VG=2.5 VD=2.5 VGLO=2.498 VGHI=2.502
  stamp "$root" "$id"
}
